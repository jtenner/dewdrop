#!/usr/bin/env python3
"""Generate compiler-owned standard identity and typed builtin-operation registry."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "tools" / "standard-builtin-registry.json"
TARGET = ROOT / "src" / "semantic" / "standard_builtin_registry.mbt"
DEW_TARGET = ROOT / "self_host" / "compiler" / "semantic_standard_builtin_registry.dew"


def rendered_dew_source() -> str:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    module = data["modules"]["wasm_intrinsics"]
    module_id = 0xFFFF0000 + module["slot"]
    return (
        "// Generated by tools/generate_standard_builtin_registry.py. Do not edit.\n"
        "// Canonical semantic type identity; no instruction implementation is selected here.\n"
        "fn self_host_standard_nullable_ref_type_declaration() -> U64 {\n"
        f"  self_host_make_semantic_id({module_id}u64, {module['nullable_ref_type']}u32)\n"
        "}\n"
    )


def rendered_source() -> str:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    modules = data["modules"]
    if any(module.get("operations") for module in modules.values()):
        raise ValueError("instruction contracts must not use declaration ordinals")
    lines = [
        "// Generated by tools/generate_standard_builtin_registry.py. Do not edit.",
        "",
    ]

    indexed_traits = data["preamble_traits"]
    lines.extend(
        [
            "///|",
            "fn standard_indexed_trait_kind(declaration : DeclId) -> Int32 {",
            "  match semantic_id_local(declaration) {",
            f"    {indexed_traits['indexed_get']} => 1",
            f"    {indexed_traits['indexed_set']} => 2",
            "    _ => 0",
            "  }",
            "}",
            "",
        ]
    )

    for module_name in (
        "array", "queue", "circular_buffer", "deque", "map", "set"
    ):
        module = modules[module_name]
        prefix = f"standard_{module_name}"
        # Type identities may still be used by literal/runtime producers after
        # all operations have moved to ordinary library calls.
        if "type" in module:
            lines.extend(
                [
                    "///|",
                    f"pub fn {prefix}_type_declaration() -> DeclId {{",
                    f"  make_semantic_id(standard_library_module_id({module.get('type_slot', module['slot'])}), {module['type']})",
                    "}",
                    "",
                ]
            )
        if "methods" in module:
            lines.extend([
                "///|",
                f"pub fn {prefix}_method_declaration(name : String) -> DeclId {{",
                "  let local_id = match name {",
            ])
            for name, ordinal in module["methods"].items():
                lines.append(f'    "{name}" => {ordinal}')
            lines.extend(
                [
                    "    _ => -1",
                    "  }",
                    "  if local_id < 0 {",
                    "    0UL",
                    "  } else {",
                    f"    make_semantic_id(standard_library_module_id({module['slot']}), local_id)",
                    "  }",
                    "}",
                    "",
                ]
            )
        if "iterator_type" in module:
            lines.extend(
                [
                    "///|",
                    f"pub fn {prefix}_iterator_type_declaration() -> DeclId {{",
                    f"  make_semantic_id(standard_library_module_id({module['slot']}), {module['iterator_type']})",
                    "}",
                    "",
                ]
            )
        for opaque_name, opaque_local in module.get("opaque_types", {}).items():
            lines.extend(
                [
                    "///|",
                    f"pub fn {prefix}_{opaque_name}_type_declaration() -> DeclId {{",
                    f"  make_semantic_id(standard_library_module_id({module['slot']}), {opaque_local})",
                    "}",
                    "",
                ]
            )
        if "index" in module:
            lines.extend(
                [
                    "///|",
                    f"pub fn {prefix}_index_declaration() -> DeclId {{",
                    f"  make_semantic_id(standard_library_module_id({module['slot']}), {module['index']})",
                    "}",
                    "",
                    "///|",
                    f"pub fn {prefix}_index_set_declaration() -> DeclId {{",
                    f"  make_semantic_id(standard_library_module_id({module['slot']}), {module['index_set']})",
                    "}",
                    "",
                ]
            )
    wasm_intrinsics = modules["wasm_intrinsics"]
    lines.extend(
        [
            "///|",
            "pub fn standard_nullable_ref_type_declaration() -> DeclId {",
            f"  make_semantic_id(standard_library_module_id({wasm_intrinsics['slot']}), {wasm_intrinsics['nullable_ref_type']})",
            "}",
            "",
        ]
    )

    option = modules["option"]
    lines.extend(
        [
            "///|",
            "fn standard_option_type_declaration() -> DeclId {",
            f"  make_semantic_id(standard_library_module_id({option['slot']}), {option['type']})",
            "}",
            "",
            "///|",
            "pub fn standard_option_none_variant() -> VariantId {",
            f"  make_semantic_id(standard_library_module_id({option['slot']}), {option['variants']['none']})",
            "}",
            "",
            "///|",
            "pub fn standard_option_some_variant() -> VariantId {",
            f"  make_semantic_id(standard_library_module_id({option['slot']}), {option['variants']['some']})",
            "}",
            "",
            "///|",
            "fn standard_lane_module_path(index : Int32) -> String {",
            "  match index {",
        ]
    )
    for index, lane in enumerate(data["lanes"]):
        if lane["slot"] != 16 + index:
            raise ValueError("lane slots must be contiguous from 16")
        lines.append(f'    {index} => "{lane["path"]}"')
    lines.extend(
        [
            '    _ => abort("unknown standard lane module slot")',
            "  }",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for target, rendered in (
        (TARGET, rendered_source()),
        (DEW_TARGET, rendered_dew_source()),
    ):
        if args.check:
            if not target.exists() or target.read_text(encoding="utf-8") != rendered:
                raise SystemExit(
                    f"{target.relative_to(ROOT)} is stale; "
                    "run tools/generate_standard_builtin_registry.py"
                )
            print(f"checked {target.relative_to(ROOT)}")
        else:
            target.write_text(rendered, encoding="utf-8")
            print(f"generated {target.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
