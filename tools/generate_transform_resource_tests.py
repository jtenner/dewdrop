#!/usr/bin/env python3
from pathlib import Path
import argparse
import hashlib
import json
import sys
import subprocess

parser = argparse.ArgumentParser(description="Generate paired Native/Dew transform resource tests.")
parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
root = args.root.resolve()
data = json.loads((root / "tools/dew-test/transform-resource-counts.json").read_text())
if data.get("version") != 1:
    raise SystemExit("unsupported transform resource count version")
for case in data["cases"]:
    raw = (root / case["path"]).read_bytes()
    if hashlib.sha256(raw).hexdigest() != case["source_sha256"]:
        raise SystemExit(f"{case['path']}: source changed; measure and update paired resource counts")
    case["source"] = raw.decode("utf-8")
def literal(s): return json.dumps(s,ensure_ascii=False)
nb=['// Generated by tools/generate_transform_resource_tests.py. Do not edit.\n']
db=['// Generated by tools/generate_transform_resource_tests.py. Do not edit.\n']
for case in data['cases']:
 name=case['name']; source='b'+literal(case['source']); path=literal(case['path']); module=literal(case['module'])
 nb.append(f'''///|
test "shared transform resource counts {name}" {{
  let manifest = @semantic.ProgramManifest::new([
    @semantic.ManifestModule::new({module}, [
      @semantic.ManifestFile::new({path}, {source}),
    ]),
  ])
  let options = CompilerPipelineOptions::production(4000UL, 0, true)
  match expand_manifest_sources(manifest, @semantic.StandardLibrarySources::bootstrap(), options) {{
    Ok(_) => ()
    Err(error) => fail(error.message())
  }}
  let reports = options.transform_reports
  assert_eq(reports.length(), {len(case['reports'])})
''')
 db.append(f'''test "shared transform resource counts {name}" {{
  let manifest = SelfHostProgramManifest::{{
    modules: [{{
      path: {module}
      files: [{{
        path: {path}
        source: {source}
        test_only: false
      }}]
    }}]
  }}
  match ct_expand_checked_with_reports(manifest, ct_frames_test_source_pool(), true) {{
    Err(error) => assert(false, error)
    Ok(expanded) => {{
      let reports = expanded.reports
      assert(reports.length() == {len(case['reports'])}u32, "report count")
''')
 for i,r in enumerate(case['reports']):
  fields=[('module_name','module'),('file_name','file'),('function_name','function'),('transform_name','transform')]
  for field,key in fields:
   nb.append(f'  assert_eq(reports[{i}].{field}, {literal(r[key])})\n')
   db.append(f'      assert(reports[{i}u32].{field} == {literal(r[key])}, "{field}")\n')
  for field,key in [('offset','offset'),('work','work'),('allocation_work','allocation_work')]:
   nb.append(f'  assert_eq(reports[{i}].{field}, {r[key]}U)\n')
  db.append(f'''      if reports[{i}u32].offset != {r['offset']}u32 || reports[{i}u32].work != {r['work']}u32 || reports[{i}u32].allocation_work != {r['allocation_work']}u32 {{
        let message = StringBuilder::new()
        message.append("{name}: expected offset/work/allocation {r['offset']}/{r['work']}/{r['allocation_work']}, got ")
        message.append_u32(reports[{i}u32].offset)
        message.append("/")
        message.append_u32(reports[{i}u32].work)
        message.append("/")
        message.append_u32(reports[{i}u32].allocation_work)
        assert(false, message.finish())
      }}
''')
 nb.append('}\n\n'); db.append('    }\n  }\n}\n\n')
outputs = {
    "src/compiler_driver/transforms_resource_reports_wbtest.mbt": subprocess.run(
        ["moonfmt", "-"], input="".join(nb), text=True, capture_output=True, check=True
    ).stdout,
    "self_host/compiler/transform_resource_reports_test.dew": "".join(db).rstrip("\n") + "\n",
}
failed = False
for relative, content in outputs.items():
    target = root / relative
    if args.check:
        if not target.is_file() or target.read_text() != content:
            print(f"{relative}: generated resource tests are stale", file=sys.stderr)
            failed = True
    else:
        target.write_text(content)
if failed:
    raise SystemExit(1)
