                    f"    Option::None => 1u32\n"
                    f"    _ => 0u32\n"
                    f"  }}\n"
                    f"  let b = match hay_string.find_view(needle_view) {{\n"
                    f"    Option::None => 1u32\n"
                    f"    _ => 0u32\n"
                    f"  }}\n"
                    f"  let c = match hay_view.find(needle_view) {{\n"
