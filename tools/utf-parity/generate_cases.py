            left_wrapped = b"l" * left_start + left + b"L"
            for right_index, right_length in enumerate(concat_lengths):
                right = bytes((offset * 43 + right_length * 9 + 3) % 256 for offset in range(right_length))
                right_wrapped = b"r" * right_start + right + b"R"
