#!/usr/bin/env python3
"""Generate direct and outlined runtime checks for every scalar instruction."""

import argparse
from pathlib import Path

from wasm_scalar_intrinsics import SCALAR_INSTRUCTIONS

ROOT = Path(__file__).resolve().parents[1]


def sample(name: str, inputs: tuple[str, ...], result: str) -> tuple[list[str], str, str]:
    kind, operation = name.split(".")
    boolean = operation in ("eqz", "eq", "ne", "lt", "gt", "le", "ge", "lt_s", "lt_u", "gt_s", "gt_u", "le_s", "le_u", "ge_s", "ge_u")
    result_type = "Bool" if boolean else result.upper()
    if operation == "eqz":
        return ["0" + kind], "true", result_type
    if operation in ("clz", "ctz", "popcnt"):
        value, expected = {"clz": (1, 31 if kind == "i32" else 63), "ctz": (8, 3), "popcnt": (7, 3)}[operation]
        return [f"{value}{kind}"], f"{expected}{kind}", result_type
    if operation.startswith("extend") and operation.endswith("_s") and not operation.startswith("extend_i"):
        bits = int(operation[6:-2])
        return [f"{(1 << bits) - 1}{kind}"], "-1" + kind, result_type
    if operation == "wrap_i64":
        return ["4294967338i64"], "42i32", result_type
    if operation.startswith("extend_i32"):
        return ["-1i32"], "-1i64" if operation.endswith("_s") else "4294967295i64", result_type
    if operation.startswith("convert_"):
        return ["6" + inputs[0]], "6.0" + kind, result_type
    if operation.startswith("trunc_sat_"):
        if operation.endswith("_u"):
            return ["-1.0" + inputs[0]], "0" + kind, result_type
        limit = "2147483648.0" if kind == "i32" else "9223372036854775808.0"
        return [limit + inputs[0]], ("2147483647i32" if kind == "i32" else "9223372036854775807i64"), result_type
    if operation.startswith("trunc_"):
        return ["6.75" + inputs[0]], "6" + kind, result_type
    if operation.startswith(("promote_", "demote_")):
        return ["1.5" + inputs[0]], "1.5" + kind, result_type
    if operation.startswith("reinterpret_"):
        bits = "1065353216" if "32" in kind else "4607182418800017408"
        return (["1.0" + inputs[0]], bits + kind, result_type) if kind.startswith("i") else ([bits + inputs[0]], "1.0" + kind, result_type)
    if kind.startswith("f") and len(inputs) == 1:
        value, expected = {"abs": ("-2.0", "2.0"), "neg": ("2.0", "-2.0"), "ceil": ("1.25", "2.0"), "floor": ("1.75", "1.0"), "trunc": ("1.75", "1.0"), "nearest": ("2.5", "2.0"), "sqrt": ("4.0", "2.0")}[operation]
        return [value + kind], expected + kind, result_type
    if boolean:
        expected = operation in ("ne", "gt", "ge", "gt_s", "gt_u", "ge_s", "ge_u")
        suffix = ".0" if kind.startswith("f") else ""
        return [f"6{suffix}{kind}", f"2{suffix}{kind}"], "true" if expected else "false", result_type
    value, right, expected = {
        "add": (6, 2, 8), "sub": (6, 2, 4), "mul": (6, 2, 12), "div": (6, 2, 3),
        "div_s": (6, 2, 3), "div_u": (6, 2, 3), "rem_s": (7, 2, 1), "rem_u": (7, 2, 1),
        "and": (6, 2, 2), "or": (6, 2, 6), "xor": (6, 2, 4), "shl": (6, 2, 24),
        "shr_s": (8, 2, 2), "shr_u": (8, 2, 2), "rotl": (6, 2, 24), "rotr": (8, 2, 2),
        "min": (6, 2, 2), "max": (6, 2, 6), "copysign": (6, -2, -6),
    }[operation]
    suffix = ".0" if kind.startswith("f") else ""
    return [f"{value}{suffix}{kind}", f"{right}{suffix}{kind}"], f"{expected}{suffix}{kind}", result_type


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    lines = ["// Generated by tools/generate_scalar_intrinsic_tests.py.", ""]
    tests = lines.copy()
    for index, (name, _, inputs, result) in enumerate(SCALAR_INSTRUCTIONS):
        values, expected, result_type = sample(name, inputs, result)
        parameters = ", ".join(f"arg{i}: {kind.upper()}" for i, kind in enumerate(inputs))
        arguments = ", ".join(values)
        lines += [f'builtin scalar_{index}({parameters}) -> {result_type} = "{name}"',
                  f"fn scalar_check_{index}() -> Bool {{", f"  let operation = scalar_{index}",
                  f"  scalar_{index}({arguments}) == {expected} && operation({arguments}) == {expected}", "}", ""]
        tests += [f'test "direct and outlined {name}" {{', f'  assert(scalar_check_{index}(), "{name} result")', "}", ""]
    lines += ["pub fn main() -> I32 {", "  let mut valid = true"]
    for index in range(len(SCALAR_INSTRUCTIONS)):
        lines.append(f"  valid = scalar_check_{index}() && valid")
    lines += ["  if valid {", "    42i32", "  } else {", "    0i32", "  }", "}", ""]
    for filename, content in [("scalar_intrinsics.dew", lines), ("scalar_intrinsics_test.dew", tests)]:
        output = ROOT / "tools/dew-test" / filename
        expected = "\n".join(content)
        if args.check:
            if output.read_text() != expected:
                raise SystemExit(f"stale {output.relative_to(ROOT)}")
        else:
            output.write_text(expected)
    print(f'{"checked" if args.check else "generated"} 136 direct/outlined scalar runtime checks')


if __name__ == "__main__":
    main()
