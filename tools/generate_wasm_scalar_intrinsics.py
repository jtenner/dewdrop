#!/usr/bin/env python3
"""Generate scalar instruction emitters and Native/Dew stack contracts."""

import argparse
from collections import defaultdict
from pathlib import Path

from wasm_scalar_intrinsics import SCALAR_INSTRUCTIONS, NUMERIC_INSTRUCTIONS, CONVERSION_INSTRUCTIONS

ROOT = Path(__file__).resolve().parents[1]
NATIVE = {kind: f"Wasm{kind.upper()}Value" for kind in ("i32", "i64", "f32", "f64")}
DEW = {kind: f"{kind.upper()}BodyCarrier" for kind in NATIVE}


def emitter(function: str, rows: list) -> str:
    lines = ["///|", "// Generated by tools/generate_wasm_scalar_intrinsics.py.",
             f"fn {function}(name : Bytes) -> Array[@lib.Instruction]? {{"]
    for index, (name, method, _, _) in enumerate(rows):
        lines += [f'  {"if" if index == 0 else "} else if"} name == b"{name}" {{',
                  f"    Some([@lib.Instruction::{method}()])"]
    return "\n".join(lines + ["  } else {", "    None", "  }", "}", ""])


def contracts(dew: bool) -> str:
    groups = defaultdict(list)
    for name, _, inputs, result in SCALAR_INSTRUCTIONS:
        groups[inputs, result].append(name)
    carrier = DEW if dew else NATIVE
    if dew:
        lines = ["// Generated by tools/generate_wasm_scalar_intrinsics.py.",
                 "fn self_host_raw_scalar_signature(name: Bytes) -> Option<SelfHostRawIntrinsicSignature> {"]
    else:
        lines = ["///|", "// Generated by tools/generate_wasm_scalar_intrinsics.py.",
                 "fn raw_wasm_scalar_signature(name : Bytes) -> RawWasmIntrinsicSignature? {", "  match name {"]
    for (inputs, result), names in groups.items():
        arguments = ", ".join(carrier[kind] for kind in inputs)
        if dew:
            lines.append("  if " + " ||\n    ".join(f'name.equals(b"{name}")' for name in names) + " {")
            lines += ["    return Some({", f"      inputs: [{arguments}]", f"      result: {carrier[result]}", "    })", "  }"]
        else:
            lines += ["    " + "\n    | ".join(f'b"{name}"' for name in names) + " =>",
                      f"      Some({{ inputs: [{arguments}], result: Some({carrier[result]}), }})"]
    lines += ["  None", "}", ""] if dew else ["    _ => None", "  }", "}", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    # Keep the existing two emitter entry points; both use one catalog.
    outputs = {
        "src/backend/starshine_numeric_builtins.mbt": emitter("starshine_numeric_builtin_instructions", NUMERIC_INSTRUCTIONS),
        "src/backend/starshine_conversion_builtins.mbt": emitter("starshine_conversion_builtin_instructions", CONVERSION_INSTRUCTIONS),
        "src/semantic/raw_wasm_scalar_intrinsics.mbt": contracts(False),
        "self_host/compiler/semantic_raw_scalar_intrinsics.dew": contracts(True),
    }
    for name, content in outputs.items():
        path = ROOT / name
        if args.check:
            if path.read_text() != content:
                raise SystemExit(f"stale {name}")
        else:
            path.write_text(content)
    print(f'{"checked" if args.check else "generated"} {len(outputs)} scalar instruction tables (136 opcodes)')


if __name__ == "__main__":
    main()
